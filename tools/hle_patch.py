#!/usr/bin/env python3
"""Mark functions in main.dol for native replacement (HLE) before recompiling.

Each listed function's first instruction is overwritten with `mfspr r0, HID0`
(0x7C10FAA6). DolRecomp always routes that instruction to the runtime's
instruction fallback, which looks the address up in the HLE table
(runtime/hle_table.h) and runs the native implementation instead.

Usage: hle_patch.py <main.dol> <symbols.txt> <hle_list.txt> <out.dol> <out_table.h>
hle_list.txt: one function name (or 0xADDRESS name) per line; '#' comments.
"""
import re
import struct
import sys

MARK = 0x7C10FAA6


def main():
    dol, syms, lst, out, table = sys.argv[1:6]
    d = bytearray(open(dol, "rb").read())
    addrs = {}
    for line in open(syms):
        m = re.match(r"(\S+) = \.\w+:0x([0-9A-Fa-f]+);", line)
        if m:
            addrs[m.group(1)] = int(m.group(2), 16)
    offs = struct.unpack(">18I", d[0:72])
    vaddr = struct.unpack(">18I", d[72:144])
    size = struct.unpack(">18I", d[144:216])

    def file_off(a):
        for i in range(7):  # text sections
            if size[i] and vaddr[i] <= a < vaddr[i] + size[i]:
                return offs[i] + (a - vaddr[i])
        raise ValueError(f"{a:#x} not in text")

    entries = []
    for line in open(lst):
        line = line.split("#")[0].strip()
        if not line:
            continue
        parts = line.split()
        if parts[0].startswith("0x"):
            a, name = int(parts[0], 16), parts[1]
        else:
            name = parts[0]
            if name not in addrs:
                sys.exit(f"unknown symbol {name}")
            a = addrs[name]
        o = file_off(a)
        orig = struct.unpack_from(">I", d, o)[0]
        struct.pack_into(">I", d, o, MARK)
        entries.append((a, name, orig))
    open(out, "wb").write(d)
    with open(table, "w") as fp:
        fp.write("/* Generated by tools/hle_patch.py. Do not edit. */\n")
        for a, name, orig in sorted(entries):
            fp.write(f"HLE_ENTRY(0x{a:08X}u, {name}, 0x{orig:08X}u)\n")
    print(f"patched {len(entries)} functions -> {out}")


if __name__ == "__main__":
    main()
